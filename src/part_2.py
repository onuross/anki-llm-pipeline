def process_daily_sources(config):
    """
    Reads mixed sources (CSV & TXT), generates TTS, pushes to Anki DB via API,
    archives the data, and performs stateful cleanup.
    """
    source_files = config["source_files"]
    cards = []
    lang = config["language"]

    # Step 1: Hybrid Data Ingestion (Parse all valid sources)
    for file_path in source_files:
        if not os.path.exists(file_path):
            continue

        with open(file_path, "r", encoding="utf-8") as f:
            if str(file_path).endswith(".txt"):
                # Headerless parsing for manual TXT fallbacks
                for line in f:
                    line = line.strip()
                    if not line:
                        continue
                    parts = line.split("|")
                    if len(parts) >= 4:
                        cards.append(
                            {
                                "sentence": " ".join(parts[0].split()),  # Updated keys
                                "base_word": " ".join(parts[1].split()),  # Updated keys
                                "meaning": " ".join(parts[2].split()),  # Updated keys
                                "translation": " ".join(
                                    parts[3].split()
                                ),  # Updated keys
                            }
                        )
            else:
                # Header-aware parsing for automated CSVs
                reader = csv.reader(f, delimiter="|")
                next(reader, None)  # Skip header
                for row in reader:
                    if len(row) >= 4:
                        cards.append(
                            {
                                "sentence": " ".join(row[0].split()),  # Updated keys
                                "base_word": " ".join(row[1].split()),  # Updated keys
                                "meaning": " ".join(row[2].split()),  # Updated keys
                                "translation": " ".join(row[3].split()),  # Updated keys
                            }
                        )

    if not cards:
        logging.info(f"ℹ️ No pending cards found for {lang}.")
        return False

    logging.info(f"\n🚀 Processing {len(cards)} cards for {lang}...")

    # Step 2: TTS Generation and Anki Injection
    successful_cards = []
    for idx, card in enumerate(cards):
        clean_sentence = clean_cloze_tags_for_tts(card["sentence"])  # Updated key
        audio_filename = f"tts_{lang}_{idx}_{int(time.time())}.mp3"

        try:
            # 2.1 Async TTS Generation
            asyncio.run(
                generate_tts_async(clean_sentence, config["voice"], audio_filename)
            )

            # 2.2 Upload Base64 Audio to Anki
            upload_media_to_anki(audio_filename)

            # 2.3 Create Anki Note Payload
            note = {
                "deckName": config["deck_name"],
                "modelName": config["note_type"],
                "fields": {
                    # Note: These exact field names MUST exist in your Anki Note Type settings!
                    config["field_sentence"]: card["sentence"],
                    "Base_Word": card[
                        "base_word"
                    ],  # Updated to match part_1 logic (Assuming Anki field is named Base_Word)
                    "Meaning": card["meaning"],  # Assuming Anki field is Meaning
                    "Translation": f"{card['translation']} [sound:{audio_filename}]",  # Assuming Anki field is Translation
                },
                "options": {"allowDuplicate": False},
                "tags": [f"Part2_{lang}", "Automated_Pipeline"],
            }

            # 2.4 Inject Note
            invoke_anki_api("addNote", note=note)
            logging.info(
                f"   ✅ {card['base_word']} -> Injected to Anki"
            )  # Updated key
            successful_cards.append(card)
            time.sleep(1)  # Brief pause to respect local API processing

        except Exception as e:
            logging.error(
                f"   ❌ Error on ({card.get('base_word')}): {e}"
            )  # Updated key

    if not successful_cards:
        logging.error(f"❌ {lang} injection failed completely.")
        return False

    # Step 3: Archival
    append_to_master_csv(
        config["main_csv_path"], successful_cards, config["field_sentence"]
    )
    logging.info(f"📚 {len(successful_cards)} cards archived to Master CSV.")

    # Step 4: Stateful Cleanup
    for file_path in source_files:
        if os.path.exists(file_path):
            clear_daily_source_file(file_path)
            logging.info(f"🗑️ Source file cleaned: {file_path.name}")

    return True


