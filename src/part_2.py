def clean_cloze_tags_for_tts(sentence):
    """
    Strips Anki cloze formatting (e.g., {{c1::word::hint}}) from the sentence
    so the TTS engine reads the text naturally without spelling out brackets.
    """
    return re.sub(r"\{\{c\d+::(.*?)(?:::.*?)?\}\}", r"\1", sentence)


async def generate_tts_async(text, voice, filename):
    """Generates an MP3 file asynchronously using Microsoft Edge TTS."""
    communicate = edge_tts.Communicate(text, voice)
    await communicate.save(filename)


def invoke_anki_api(action, **params):
    """
    Sends a payload to the local AnkiConnect REST API.
    Provides robust error handling if Anki is closed or unresponsive.
    """
    request_json = {"action": action, "params": params, "version": 6}
    try:
        response = requests.post("http://localhost:8765", json=request_json).json()
        if response.get("error"):
            raise Exception(response["error"])
        return response["result"]
    except requests.exceptions.ConnectionError:
        raise Exception(
            "Anki connection failed! Please ensure Anki is running in the background."
        )


def upload_media_to_anki(filename):
    """Converts the MP3 file to Base64 and injects it into Anki's media collection."""
    with open(filename, "rb") as f:
        b64_data = base64.b64encode(f.read()).decode("utf-8")
    invoke_anki_api("storeMediaFile", filename=filename, data=b64_data)
    os.remove(filename)  # Cleanup local audio file after injection


def append_to_master_csv(file_path, flashcards, field_sentence_name):
    """Appends successfully injected flashcards to the Master Archival CSV."""
    file_exists = os.path.exists(file_path)
    with open(file_path, "a", encoding="utf-8", newline="") as f:
        writer = csv.writer(f, delimiter="|")
        if not file_exists:
            # ENGLISH HEADERS APPLIED HERE
            writer.writerow(
                [field_sentence_name, "Base_Word", "Meaning", "Translation"]
            )
        for card in flashcards:
            writer.writerow(
                [
                    card.get("sentence", ""),  # Updated keys
                    card.get("base_word", ""),  # Updated keys
                    card.get("meaning", ""),  # Updated keys
                    card.get("translation", ""),  # Updated keys
                ]
            )


def clear_daily_source_file(file_path):
    """
    Stateful cleanup: Empties the processed files to prevent duplicate injections.
    Retains the header for CSV files, entirely clears TXT files.
    """
    file_path = str(file_path)
    if not os.path.exists(file_path):
        return

    if file_path.endswith(".txt"):
        open(file_path, "w", encoding="utf-8").close()
    else:
        # Keep CSV header
        with open(file_path, "r", encoding="utf-8") as f:
            header = f.readline()
        with open(file_path, "w", encoding="utf-8") as f:
            f.write(header)


